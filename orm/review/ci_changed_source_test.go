// A listed test addition is a legitimate nonempty source change. Both package
// variants must still participate in analysis and input validation.
func TestCIChangedSourceAddedTest(t *testing.T) {
	base, head := ciFixture(t)
	before := "package fixture\nimport \"testing\"\nfunc TestBefore(t *testing.T) {}\n"
	after := before + "func TestAfter(t *testing.T) {}\n"
	for root, source := range map[string]string{base: before, head: after} {
		if err := os.WriteFile(filepath.Join(root, "sample_test.go"), []byte(source), 0600); err != nil {
			t.Fatal("fixture write failed")
		}
	}
	patch := []byte("diff --git a/sample_test.go b/sample_test.go\n--- a/sample_test.go\n+++ b/sample_test.go\n@@ -3 +3,2 @@\n func TestBefore(t *testing.T) {}\n+func TestAfter(t *testing.T) {}\n")
	bt, be := readTree(context.Background(), base)
	ht, he := readTree(context.Background(), head)
	if be != nil || he != nil || !parseDiff(patch, bt, ht).valid {
		t.Fatal("fixture diff does not reconstruct source")
	}
	bc, hc := &ciCapture{}, &ciCapture{}
	for root, capture := range map[string]*ciCapture{base: bc, head: hc} {
		if _, err := Run(Options{Paths: []string{root}, capture: capture}); err != nil {
			t.Fatal("capture failed")
		}
	}
	// Report only fixed classifications/counts, never source paths or bytes.
	externalBase, externalHead, equalExternalBytes := 0, 0, 0
	generatedBase, generatedHead := 0, 0
	generatedMarker := []byte("// Code generated by 'go test'. DO NOT EDIT.")
	for p, b := range bc.inputs {
		if relativeFile(base, p) == "" {
			externalBase++
			if bytes.Equal(hc.inputs[p], b) {
				equalExternalBytes++
			} else if bytes.Contains(b, generatedMarker) {
				generatedBase++
			}
		}
	}
	for p := range hc.inputs {
		if relativeFile(head, p) == "" {
			externalHead++
			if !bytes.Equal(bc.inputs[p], hc.inputs[p]) && bytes.Contains(hc.inputs[p], generatedMarker) {
				generatedHead++
			}
		}
	}
	t.Logf("base_valid=%t head_valid=%t external_equal=%t external_base=%d external_head=%d exact_matches=%d", captureValid(bc, base, bt), captureValid(hc, head, ht), equalExternalCaptures(bc, hc, base, head), externalBase, externalHead, equalExternalBytes)
	t.Logf("unmatched_go_test_generated_base=%d unmatched_go_test_generated_head=%d", generatedBase, generatedHead)
	r, err := RunCI(Options{}, CIOptions{Root: head, BaseRoot: base, Diff: patch, FailOn: query.RiskMedium, FailOnPrecision: query.AnalysisPartial})
	if err != nil {
		t.Fatal("comparison failed")
	}
	if r.invalid || r.ExitCode() != 1 || !r.risk || !r.precision {
		t.Fatalf("input_failed=%t exit=%d risk_failed=%t precision_failed=%t diff=%+v findings=%+v", r.invalid, r.ExitCode(), r.risk, r.precision, r.diff, r.findings)
	}
}

func changedFixturePatch(old, head map[string]string) []byte {
	var b strings.Builder
	paths := map[string]bool{}
	for p := range old {
		paths[p] = true
	}
	for p := range head {
		paths[p] = true
	}
	keys := make([]string, 0, len(paths))
	for p := range paths {
		keys = append(keys, p)
	}
	sort.Strings(keys)
	for _, p := range keys {
		a, aok := old[p]
		z, zok := head[p]
		if aok == zok && a == z {
			continue
		}
		fmt.Fprintf(&b, "diff --git a/%s b/%s\n", p, p)
		if aok {
			fmt.Fprintf(&b, "--- a/%s\n", p)
		} else {
			b.WriteString("--- /dev/null\n")
		}
		if zok {
			fmt.Fprintf(&b, "+++ b/%s\n", p)
		} else {
			b.WriteString("+++ /dev/null\n")
		}
		al, zl := textLines([]byte(a)), textLines([]byte(z))
		as, zs := 1, 1
		if len(al) == 0 {
			as = 0
		}
		if len(zl) == 0 {
			zs = 0
		}
		fmt.Fprintf(&b, "@@ -%d,%d +%d,%d @@\n", as, len(al), zs, len(zl))
		for _, l := range al {
			fmt.Fprintf(&b, "-%s\n", l)
		}
		for _, l := range zl {
			fmt.Fprintf(&b, "+%s\n", l)
		}
	}
	return []byte(b.String())
}

func TestCIChangedSourceTestVariants(t *testing.T) {
	internal := "package fixture\nimport \"testing\"\nfunc TestOne(t *testing.T) {}\n"
	external := strings.ReplaceAll(internal, "package fixture", "package fixture_test")
	mainTest := internal + "func TestMain(m *testing.M) { m.Run() }\n"
	pkg := map[string]string{"child/a.go": "package child\n", "child/a_test.go": strings.ReplaceAll(internal, "package fixture", "package child")}
	cases := []struct {
		name      string
		old, head map[string]string
	}{
		{"internal_added", nil, map[string]string{"a_test.go": internal}},
		{"internal_deleted", map[string]string{"a_test.go": internal}, nil},
		{"external_added", nil, map[string]string{"a_test.go": external}},
		{"external_modified", map[string]string{"a_test.go": external}, map[string]string{"a_test.go": external + "func TestTwo(t *testing.T) {}\n"}},
		{"testmain_added", map[string]string{"a_test.go": internal}, map[string]string{"a_test.go": mainTest}},
		{"testmain_deleted", map[string]string{"a_test.go": mainTest}, map[string]string{"a_test.go": internal}},
		{"package_added", nil, pkg},
		{"package_deleted", pkg, nil},
		{"multiple_packages", pkg, map[string]string{"child/a.go": "package child\n", "child/a_test.go": pkg["child/a_test.go"] + "func TestTwo(t *testing.T) {}\n", "a_test.go": external}},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			base, head := ciFixture(t)
			// Keep the external testing dependency set present on both sides.
			// Only the number/bytes of unused executable roots may differ.
			for _, root := range []string{base, head} {
				if os.WriteFile(filepath.Join(root, "stable_test.go"), []byte(strings.ReplaceAll(internal, "TestOne", "TestStable")), 0600) != nil {
					t.Fatal("fixture write")
				}
			}
			for root, files := range map[string]map[string]string{base: tc.old, head: tc.head} {
				for p, s := range files {
					full := filepath.Join(root, p)
					if os.MkdirAll(filepath.Dir(full), 0700) != nil || os.WriteFile(full, []byte(s), 0600) != nil {
						t.Fatal("fixture write")
					}
				}
			}
			patch := changedFixturePatch(tc.old, tc.head)
			r, err := RunCI(Options{}, CIOptions{Root: head, BaseRoot: base, Diff: patch, FailOn: query.RiskMedium, FailOnPrecision: query.AnalysisPartial})
			if err != nil || r.invalid || r.ExitCode() != 1 || !r.risk || !r.precision || r.diff.Unknown != 0 {
				t.Fatalf("comparison exit=%d diff=%+v", r.ExitCode(), r.diff)
			}
			if r.findings.Unchanged != 0 || r.findings.Unknown == 0 {
				t.Fatal("changed context promoted unchanged findings")
			}
		})
	}
}

func TestCICaptureRetainsExactBytes(t *testing.T) {
	root := t.TempDir()
	external := filepath.Join(t.TempDir(), "_testmain.go")
	original := []byte("// Code generated by 'go test'. DO NOT EDIT.\npackage main\n")
	if os.WriteFile(external, original, 0600) != nil {
		t.Fatal("write")
	}
	c := &ciCapture{valid: true, inputs: map[string][]byte{external: original}, unusedTestMain: map[string]bool{external: true}}
	if !captureValid(c, root, sourceTree{}) {
		t.Fatal("valid capture")
	}
	// Even a proven unused executable is checked for same-session mutation.
	if os.WriteFile(external, append(append([]byte{}, original...), []byte("// changed\n")...), 0600) != nil {
		t.Fatal("write")
	}
	if captureValid(c, root, sourceTree{}) {
		t.Fatal("mutation accepted")
	}
	c.unusedTestMain = nil
	other := &ciCapture{valid: true, inputs: map[string][]byte{external: []byte("different\n")}}
	if equalExternalCaptures(c, other, root, root) {
		t.Fatal("external bytes ignored")
	}
	other.inputs = map[string][]byte{filepath.Join(t.TempDir(), "_testmain.go"): original}
	if equalExternalCaptures(c, other, root, root) {
		t.Fatal("external path ignored")
	}
	local := filepath.Join(root, "a.go")
	c = &ciCapture{valid: true, inputs: map[string][]byte{local: original}}
	if captureValid(c, root, sourceTree{"a.go": []byte("different\n")}) || captureValid(c, root, sourceTree{}) {
		t.Fatal("stale or unlisted source accepted")
	}
}

// Adding the first test also adds consumed standard-library sources. Those
// ordinary external inputs remain subject to exact set/path/byte agreement.
func TestCIChangedSourceNewExternalContextRemainsUnknown(t *testing.T) {
	base, head := ciFixture(t)
	source := "package fixture\nimport \"testing\"\nfunc TestFirst(t *testing.T) {}\n"
	if os.WriteFile(filepath.Join(head, "a_test.go"), []byte(source), 0600) != nil {
		t.Fatal("write")
	}
	patch := changedFixturePatch(nil, map[string]string{"a_test.go": source})
	r, e := RunCI(Options{}, CIOptions{Root: head, BaseRoot: base, Diff: patch})
	if e != nil || !r.invalid || r.ExitCode() != 2 || r.diff.Unknown == 0 {
		t.Fatal("new consumed external context silently ignored")
	}
}

func TestCIChangedSourceTestRename(t *testing.T) {
	base, head := ciFixture(t)
	source := []byte("package fixture\nimport \"testing\"\nfunc TestOne(t *testing.T) {}\n")
	for p := range map[string]bool{filepath.Join(base, "before_test.go"): true, filepath.Join(head, "after_test.go"): true} {
		if os.WriteFile(p, source, 0600) != nil {
			t.Fatal("write")
		}
	}
	patch := []byte("diff --git a/before_test.go b/after_test.go\nsimilarity index 100%\nrename from before_test.go\nrename to after_test.go\n")
	r, e := RunCI(Options{}, CIOptions{Root: head, BaseRoot: base, Diff: patch, FailOn: query.RiskMedium})
	if e != nil || r.invalid || r.diff.Renamed != 1 || r.ExitCode() != 1 {
		t.Fatal("rename correspondence")
	}
}
